const { test } = require('node:test')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { LearningService } = require('../dist/learning/learning.service')
const { AssignmentsService } = require('../dist/assignments/assignments.service')
const { assignmentsDb, learningRepo, iso, person } = require('./assignments-helpers.cjs')

const status = async promise => { try { await promise; return 200 } catch (error) { return error.getStatus?.() ?? error } }
function fixture() {
  const teacher = person('teacher', 'docente'), otherTeacher = person('teacher', 'otro_docente'), admin = person('admin', 'admin')
  const ana = person('student', 'ana'), beto = person('student', 'beto'), outsider = person('student', 'externa')
  const room = { id: randomUUID(), teacher_id: teacher.id, name: 'Salón A', status: 'active' }
  const enrollments = new Set([room.id + ':' + ana.id, room.id + ':' + beto.id])
  const users = [teacher, otherTeacher, admin, ana, beto, outsider]
  const project = (owner, classroom_id, extra = {}) => ({ id: randomUUID(), owner_id: owner.id, classroom_id, title: 'Proyecto de ' + owner.username, project_type: 'image_classification', status: 'draft', ...extra })
  const anaProject = project(ana, room.id), anaSecond = project(ana, room.id), anaPersonal = project(ana, null), anaArchived = project(ana, room.id, { status: 'archived' })
  const betoProject = project(beto, room.id)
  const projects = [anaProject, anaSecond, anaPersonal, anaArchived, betoProject]
  const runs = [1, 2].map(n => ({ project_id: anaProject.id, run_number: n, metrics_json: JSON.stringify({ test_accuracy: n === 2 ? 0.9 : 0.6 }) }))
  const coTeachers = new Set()
  const store = assignmentsDb({ rooms: [room], enrollments, users, projects, runs, coTeachers })
  const learning = new LearningService(learningRepo({ rooms: [room], enrollments, users, coTeachers }), {}, store.db)
  return { ...store, service: new AssignmentsService(learning, store.db), room, enrollments, coTeachers, teacher, otherTeacher, admin, ana, beto, outsider, anaProject, anaSecond, anaPersonal, anaArchived, betoProject }
}
const task = (over = {}) => ({ title: 'Clasificador de frutas', description: 'Entrena un clasificador de frutas.', instructions: 'Usa al menos tres frutas.', starts_at: iso(-1), ends_at: iso(7), grade_min: 0, grade_max: 20, ...over })

test('the classroom teacher and the administrator create tasks with valid dates and grade range', async () => {
  const f = fixture()
  assert.equal(await status(f.service.create(f.teacher, f.room.id, task({ ends_at: iso(-2) }))), 400, 'cierre antes del inicio')
  assert.equal(await status(f.service.create(f.teacher, f.room.id, task({ grade_min: 20, grade_max: 20 }))), 400)
  assert.equal(await status(f.service.create(f.teacher, f.room.id, task({ grade_max: 19.55 }))), 400, 'un decimal como máximo')
  assert.equal(await status(f.service.create(f.otherTeacher, f.room.id, task())), 404)
  assert.equal(await status(f.service.create(f.ana, f.room.id, task())), 404)
  const created = await f.service.create(f.teacher, f.room.id, task({ grade_min: 1, grade_max: 7.5 }))
  assert.equal(created.state, 'open'); assert.equal(created.grade_max, 7.5)
  assert.equal((await f.service.create(f.admin, f.room.id, task({ title: 'Del administrador' }))).classroom_id, f.room.id)
  f.room.status = 'archived'
  assert.equal(await status(f.service.create(f.teacher, f.room.id, task())), 400, 'salón archivado')
})

test('students see tasks of their classroom; before the start only the title and dates', async () => {
  const f = fixture()
  await f.service.create(f.teacher, f.room.id, task({ title: 'Próxima', starts_at: iso(2), ends_at: iso(9) }))
  await f.service.create(f.teacher, f.room.id, task({ title: 'Abierta' }))
  const list = await f.service.list(f.ana, f.room.id)
  const upcoming = list.find(t => t.title === 'Próxima'), open = list.find(t => t.title === 'Abierta')
  assert.equal(upcoming.state, 'upcoming'); assert.equal(upcoming.description, null); assert.equal(upcoming.instructions, null)
  assert.equal(open.state, 'open'); assert.equal(open.instructions, 'Usa al menos tres frutas.'); assert.equal(open.my_submission, null)
  assert.equal(await status(f.service.list(f.outsider, f.room.id)), 404)
  const teacherView = await f.service.list(f.teacher, f.room.id)
  assert.deepEqual(teacherView.find(t => t.title === 'Abierta').counts, { students: 2, submitted: 0, graded: 0 })
  assert.equal(teacherView.find(t => t.title === 'Próxima').description, 'Entrena un clasificador de frutas.')
})

test('a submission is one of the student own projects of the classroom; it records the training and can be replaced until graded', async () => {
  const f = fixture()
  const upcoming = await f.service.create(f.teacher, f.room.id, task({ starts_at: iso(1), ends_at: iso(3) }))
  assert.equal(await status(f.service.submit(f.ana, upcoming.id, { project_id: f.anaProject.id })), 409, 'todavía no empieza')
  const open = await f.service.create(f.teacher, f.room.id, task())
  assert.equal(await status(f.service.submit(f.ana, open.id, { project_id: f.anaPersonal.id })), 400, 'proyecto personal')
  assert.equal(await status(f.service.submit(f.ana, open.id, { project_id: f.betoProject.id })), 400, 'proyecto ajeno')
  assert.equal(await status(f.service.submit(f.ana, open.id, { project_id: f.anaArchived.id })), 400, 'proyecto archivado')
  assert.equal(await status(f.service.submit(f.teacher, open.id, { project_id: f.anaProject.id })), 403)
  assert.equal(await status(f.service.submit(f.outsider, open.id, { project_id: f.anaProject.id })), 404)
  let detail = await f.service.submit(f.ana, open.id, { project_id: f.anaSecond.id, comment: 'Primera versión' })
  assert.equal(detail.submission.project_id, f.anaSecond.id); assert.equal(detail.submission.run_number, null)
  detail = await f.service.submit(f.ana, open.id, { project_id: f.anaProject.id, comment: 'Con dos entrenamientos' })
  assert.equal(detail.submission.run_number, 2); assert.equal(detail.submission.comment, 'Con dos entrenamientos')
  assert.equal(f.submissions.length, 1, 'una entrega por alumno')
  assert.deepEqual(detail.projects.map(p => p.id).sort(), [f.anaProject.id, f.anaSecond.id, f.anaArchived.id].sort())
  const teacherView = await f.service.detail(f.teacher, open.id)
  const ana = teacherView.submissions.find(s => s.student.id === f.ana.id), beto = teacherView.submissions.find(s => s.student.id === f.beto.id)
  assert.equal(ana.submission.test_accuracy, 0.9); assert.equal(ana.submission.project.title, 'Proyecto de ana')
  assert.equal(beto.submission, null)
})

test('the teacher grades inside the range; a graded submission and the range become fixed', async () => {
  const f = fixture()
  const open = await f.service.create(f.teacher, f.room.id, task())
  assert.equal(await status(f.service.grade(f.teacher, open.id, f.ana.id, { grade: 15 })), 404, 'sin entrega')
  await f.service.submit(f.ana, open.id, { project_id: f.anaProject.id })
  assert.equal(await status(f.service.grade(f.teacher, open.id, f.ana.id, { grade: 21 })), 400)
  assert.equal(await status(f.service.grade(f.teacher, open.id, f.ana.id, { grade: 15.25 })), 400)
  assert.equal(await status(f.service.grade(f.otherTeacher, open.id, f.ana.id, { grade: 15 })), 404)
  assert.equal(await status(f.service.update(f.teacher, open.id, { grade_max: 10 })), 200, 'sin notas, el rango se puede cambiar')
  await f.service.update(f.teacher, open.id, { grade_max: 20 })
  await f.service.grade(f.teacher, open.id, f.ana.id, { grade: 17.5, feedback: 'Buen dataset' })
  const mine = await f.service.detail(f.ana, open.id)
  assert.equal(mine.submission.grade, 17.5); assert.equal(mine.submission.feedback, 'Buen dataset')
  assert.equal(await status(f.service.submit(f.ana, open.id, { project_id: f.anaSecond.id })), 409, 'ya calificada')
  assert.equal(await status(f.service.update(f.teacher, open.id, { grade_max: 10 })), 409, 'rango fijo con notas')
  assert.equal(await status(f.service.update(f.teacher, open.id, { instructions: 'Nueva consigna', ends_at: iso(10) })), 200)
  assert.equal(await status(f.service.remove(f.teacher, open.id)), 409, 'con entregas no se elimina')
  const empty = await f.service.create(f.teacher, f.room.id, task({ title: 'Sin entregas' }))
  assert.equal(await status(f.service.remove(f.teacher, empty.id)), 200)
  assert.equal(await status(f.service.detail(f.teacher, empty.id)), 404)
})

test('after the close no submissions are accepted, but the teacher can still grade', async () => {
  const f = fixture()
  const created = await f.service.create(f.teacher, f.room.id, task())
  await f.service.submit(f.beto, created.id, { project_id: f.betoProject.id })
  f.assignments.find(a => a.id === created.id).ends_at = new Date(Date.now() - 1000)
  assert.equal(await status(f.service.submit(f.ana, created.id, { project_id: f.anaProject.id })), 409, 'ya cerró')
  assert.equal((await f.service.grade(f.teacher, created.id, f.beto.id, { grade: 12 })).state, 'closed')
  // Un alumno retirado del salón sigue apareciendo con su entrega.
  f.enrollments.delete(f.room.id + ':' + f.beto.id)
  const view = await f.service.detail(f.teacher, created.id)
  assert.equal(view.submissions.find(s => s.student.id === f.beto.id).enrolled, false)
})

test('home pending lists: open tasks not yet submitted for students, ungraded submissions for teachers', async () => {
  const f = fixture()
  const first = await f.service.create(f.teacher, f.room.id, task({ title: 'Primera' }))
  await f.service.create(f.teacher, f.room.id, task({ title: 'Futura', starts_at: iso(3), ends_at: iso(5) }))
  assert.deepEqual((await f.service.pending(f.ana)).tasks.map(t => [t.title, t.classroom_name]), [['Primera', 'Salón A']])
  await f.service.submit(f.ana, first.id, { project_id: f.anaProject.id })
  assert.equal((await f.service.pending(f.ana)).tasks.length, 0)
  assert.equal((await f.service.pending(f.beto)).tasks.length, 1)
  assert.deepEqual((await f.service.pending(f.teacher)).to_grade.map(t => [t.title, t.ungraded]), [['Primera', 1]])
  assert.equal((await f.service.pending(f.otherTeacher)).to_grade.length, 0)
  assert.equal((await f.service.pending(f.admin)).to_grade.length, 1)
  await f.service.grade(f.teacher, first.id, f.ana.id, { grade: 18 })
  assert.equal((await f.service.pending(f.teacher)).to_grade.length, 0)
})

test('an additional teacher of the classroom manages its tasks like the responsible teacher', async () => {
  const f = fixture()
  assert.equal(await status(f.service.create(f.otherTeacher, f.room.id, task())), 404)
  f.coTeachers.add(f.room.id + ':' + f.otherTeacher.id)
  const created = await f.service.create(f.otherTeacher, f.room.id, task({ title: 'Del docente adicional' }))
  await f.service.submit(f.ana, created.id, { project_id: f.anaProject.id })
  assert.deepEqual((await f.service.pending(f.otherTeacher)).to_grade.map(t => t.title), ['Del docente adicional'])
  assert.equal((await f.service.detail(f.otherTeacher, created.id)).manage, true)
  await f.service.grade(f.otherTeacher, created.id, f.ana.id, { grade: 16 })
  assert.equal((await f.service.detail(f.ana, created.id)).submission.grade, 16)
  assert.equal((await f.service.detail(f.teacher, created.id)).submissions.find(s => s.student.id === f.ana.id).submission.grade, 16)
})
